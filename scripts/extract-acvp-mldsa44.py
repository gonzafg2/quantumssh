#!/usr/bin/env python3
"""Extracts the ML-DSA-44 cases of NIST's ACVP-Server vectors (ADR-0035).

ADR-0035 §Decision 5 names the sources:
gen-val/json-files/ML-DSA-keyGen-FIPS204, ML-DSA-sigGen-FIPS204 and
ML-DSA-sigVer-FIPS204. This script reads their internalProjection.json
files, which carry both the inputs and the expected outputs, and writes
the ML-DSA-44 groups the composite host key relies on, in the line format
crates/quantumssh-core/tests/acvp_mldsa44.rs parses:

- keyGen;
- sigGen and sigVer through the internal interface (FIPS 204
  Sign_internal and Verify_internal), signing deterministic and hedged;
- sigGen (deterministic) and sigVer through the external interface with
  a context string, the pure framing the composite signs with.

Usage:
  extract-acvp-mldsa44.py COMMIT KEYGEN_JSON SIGGEN_JSON SIGVER_JSON > OUT

COMMIT is the ACVP-Server commit the three files were fetched at. It is
recorded in the output header with each file's SHA-256.
"""

import hashlib
import json
import sys

PARAMETER_SET = "ML-DSA-44"

# section -> (source, group filter, the fields each case keeps, in output order)
SECTIONS = [
    ("keyGen", "keyGen", lambda _: True, ["seed", "pk", "sk"]),
    (
        "sigGen-internal-deterministic",
        "sigGen",
        lambda g: g["signatureInterface"] == "internal"
        and not g["externalMu"]
        and g["deterministic"],
        ["sk", "message", "signature"],
    ),
    (
        "sigGen-internal-hedged",
        "sigGen",
        lambda g: g["signatureInterface"] == "internal"
        and not g["externalMu"]
        and not g["deterministic"],
        ["sk", "message", "rnd", "signature"],
    ),
    (
        "sigGen-external-deterministic",
        "sigGen",
        lambda g: g["signatureInterface"] == "external"
        and g["preHash"] == "pure"
        and g["deterministic"],
        ["sk", "message", "context", "signature"],
    ),
    (
        "sigVer-internal",
        "sigVer",
        lambda g: g["signatureInterface"] == "internal" and not g["externalMu"],
        ["pk", "message", "signature", "testPassed"],
    ),
    (
        "sigVer-external",
        "sigVer",
        lambda g: g["signatureInterface"] == "external" and g["preHash"] == "pure",
        ["pk", "message", "context", "signature", "testPassed"],
    ),
]


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    return v.lower()


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    commit = sys.argv[1]
    paths = dict(zip(("keyGen", "sigGen", "sigVer"), sys.argv[2:]))
    documents = {}
    for name, path in paths.items():
        with open(path, encoding="utf-8") as f:
            documents[name] = json.load(f)
    out = sys.stdout
    out.write("# ML-DSA-44 conformance vectors from NIST ACVP-Server (ADR-0035).\n")
    out.write(f"# Commit {commit}:\n")
    for name, path in paths.items():
        out.write(f"#   ML-DSA-{name}-FIPS204/internalProjection.json sha256 {sha256(path)}\n")
    out.write("# Generated by scripts/extract-acvp-mldsa44.py. Do not edit by hand.\n")
    for section, source, keep, fields in SECTIONS:
        groups = [
            g
            for g in documents[source]["testGroups"]
            if g["parameterSet"] == PARAMETER_SET and keep(g)
        ]
        if len(groups) != 1:
            sys.exit(f"{section}: expected one group, found {len(groups)}")
        out.write(f"\n[{section}]\n")
        for test in groups[0]["tests"]:
            out.write(f"\ntcId = {test['tcId']}\n")
            for name in fields:
                out.write(f"{name} = {value(test[name])}\n")


if __name__ == "__main__":
    main()
