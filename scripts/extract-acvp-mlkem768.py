#!/usr/bin/env python3
"""Extracts the ML-KEM-768 cases of NIST's ACVP-Server vectors (#216).

RFC-0003 §"Test vectors and KAT plan" names the sources:
gen-val/json-files/ML-KEM-keyGen-FIPS203 and ML-KEM-encapDecap-FIPS203.
This script reads their internalProjection.json files, which carry both
the inputs and the expected outputs, and writes the ML-KEM-768 groups in
the line format crates/quantumssh-core/tests/acvp_mlkem.rs parses.

Usage:
  extract-acvp-mlkem768.py COMMIT KEYGEN_JSON ENCAPDECAP_JSON > OUT

COMMIT is the ACVP-Server commit the two files were fetched at. It is
recorded in the output header with each file's SHA-256.
"""

import hashlib
import json
import sys

PARAMETER_SET = "ML-KEM-768"

# function -> the fields each case keeps, in output order.
FIELDS = {
    "keyGen": ["d", "z", "ek", "dk"],
    "encapsulation": ["ek", "m", "c", "k"],
    "decapsulation": ["dk", "c", "k"],
    "encapsulationKeyCheck": ["ek", "testPassed"],
    "decapsulationKeyCheck": ["dk", "testPassed"],
}


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def groups(path, default_function):
    with open(path, encoding="utf-8") as f:
        document = json.load(f)
    for group in document["testGroups"]:
        if group["parameterSet"] != PARAMETER_SET:
            continue
        yield group.get("function", default_function), group["tests"]


def value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    return v.lower()


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    commit, keygen, encapdecap = sys.argv[1:]
    out = sys.stdout
    out.write("# ML-KEM-768 conformance vectors from NIST ACVP-Server (#216).\n")
    out.write(f"# Commit {commit}:\n")
    out.write(f"#   ML-KEM-keyGen-FIPS203/internalProjection.json sha256 {sha256(keygen)}\n")
    out.write(f"#   ML-KEM-encapDecap-FIPS203/internalProjection.json sha256 {sha256(encapdecap)}\n")
    out.write("# Generated by scripts/extract-acvp-mlkem768.py. Do not edit by hand.\n")
    sections = list(groups(keygen, "keyGen")) + list(groups(encapdecap, None))
    for function, tests in sections:
        fields = FIELDS[function]
        out.write(f"\n[{function}]\n")
        for test in tests:
            out.write(f"\ntcId = {test['tcId']}\n")
            for name in fields:
                out.write(f"{name} = {value(test[name])}\n")


if __name__ == "__main__":
    main()
